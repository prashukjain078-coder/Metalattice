def generate_stress_strain_curves(
    e_stiff: float,
    e_soft: float,
    stiffest_curve: np.ndarray,
    n_points_per_type: int = 10000,
    n_strain_points: int = 128,
    strain_max: float = 0.30
) -> Dict[str, np.ndarray]:
    """
    # RECONSTRUCTED from Paper page 19 "Target responses: Stress-strain" and Fig. 3A.
    Generates 40,000 curves by linearly sampling k with 10,000 points for each curve type:
      - Type (i): rescales response of stiffest lattice by k in [1.1, 2.0]
      - Type (ii): sigma = 0.1 * E_stiff * (eps + k * eps^2), k in [1, 10]
      - Type (iii): sigma = 0.5 * E_stiff * (eps - k * eps^2), k in [1, 3]
      - Type (iv): sigma = k * E_soft * eps, k in [0.1, 0.9]
    """
    eps = np.linspace(0.0, strain_max, n_strain_points)
    
    # Type (i): Rescaling stiffest/strongest curve by k in [1.1, 2.0]
    k_type_1 = np.linspace(1.1, 2.0, n_points_per_type)
    curves_type_1 = np.array([k * stiffest_curve for k in k_type_1])

    # Type (ii): sigma = 0.1 * E_stiff * (eps + k * eps^2), k in [1, 10]
    k_type_2 = np.linspace(1.0, 10.0, n_points_per_type)
    curves_type_2 = np.array([0.1 * e_stiff * (eps + k * (eps ** 2)) for k in k_type_2])

    # Type (iii): sigma = 0.5 * E_stiff * (eps - k * eps^2), k in [1, 3]
    k_type_3 = np.linspace(1.0, 3.0, n_points_per_type)
    curves_type_3 = np.array([0.5 * e_stiff * (eps - k * (eps ** 2)) for k in k_type_3])

    # Type (iv): sigma = k * E_soft * eps, k in [0.1, 0.9]
    k_type_4 = np.linspace(0.1, 0.9, n_points_per_type)
    curves_type_4 = np.array([k * e_soft * eps for k in k_type_4])

    return {
        'type_i': curves_type_1,
        'type_ii': curves_type_2,
        'type_iii': curves_type_3,
        'type_iv': curves_type_4,
        'strain': eps
    }


def generate_wave_transmission_sequences(
    seed: int = 1
) -> Dict[str, np.ndarray]:
    """
    # RECONSTRUCTED from Paper page 19 "Target responses: Wave transmission" and Fig. 3D.
    Discretizes frequency range into 16 intervals, initialized with '1's.
    Two attenuation gaps ('0's) of size 0 < n < 8 randomly dispersed without overlapping.
    Delta_f = (n / 16) * 11 kHz.
    Type (i): n = 2 (Delta_f ~ 1.4 kHz), 55 sequences generated.
    Type (ii): n = 3 (Delta_f ~ 2.1 kHz), 28 sequences generated.
    Type (iii): n = 4 (Delta_f ~ 2.7 kHz), 10 sequences generated.
    """
    rng = np.random.RandomState(seed)

    def generate_for_gap_size(n: int, target_count: int) -> np.ndarray:
        valid_sequences = set()
        # Enumerate or randomly sample non-overlapping gap positions
        # Gap 1 starts at p1 in [0, 16 - 2*n], length n: [p1, p1 + n)
        # Gap 2 starts at p2 in [p1 + n, 16 - n], length n: [p2, p2 + n)
        possible_pairs = []
        for p1 in range(0, 16 - 2 * n + 1):
            for p2 in range(p1 + n, 16 - n + 1):
                possible_pairs.append((p1, p2))
        
        # Shuffle pairs
        rng.shuffle(possible_pairs)
        seqs = []
        for p1, p2 in possible_pairs[:target_count]:
            vec = np.ones(16, dtype=int)
            vec[p1:p1 + n] = 0
            vec[p2:p2 + n] = 0
            seqs.append(vec)
        return np.array(seqs)

    seq_type_1 = generate_for_gap_size(n=2, target_count=55)
    seq_type_2 = generate_for_gap_size(n=3, target_count=28)
    seq_type_3 = generate_for_gap_size(n=4, target_count=10)

    return {
        'type_i': seq_type_1,
        'type_ii': seq_type_2,
        'type_iii': seq_type_3
    }


def generate_ev_constant_transmission_curves(
    n_curves: int = 1000,
    n_freq_points: int = 128
) -> np.ndarray:
    """
    # RECONSTRUCTED from Paper page 19 "Target responses: Wave transmission" and Fig. 4H.
    Constant transmission responses from 5 down to -40 dB in the frequency range 1 - 12 kHz.
    1,000 curves generated.
    """
    levels = np.linspace(5.0, -40.0, n_curves)
    curves = np.array([np.full(n_freq_points, lvl) for lvl in levels])
    return curves


